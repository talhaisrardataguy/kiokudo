// Wrap a Japanese term so tapping it opens its translation.
export function jp(term, extraClass = '') {
  const g = GLOSSARY[term];
  if (!g) return term;
  return `<span class="jp ${extraClass}" role="button" tabindex="0" lang="ja" data-jp="${term}" aria-label="${term}, ${g.r}: ${g.m}">${term}</span>`;
}
